                    SELECT COUNT(*) FROM MAINTENANCE_COMPLIANCE_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
            END = EXPECTED_ROWS THEN 'LOADED'

            WHEN CASE FILE_NAME
                WHEN 'equipment.csv' THEN (
                    SELECT COUNT(*) FROM EQUIPMENT_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'usage_clean.csv' THEN (
                    SELECT COUNT(*) FROM USAGE_CLEAN_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'maintenance.csv' THEN (
                    SELECT COUNT(*) FROM MAINTENANCE_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'calibration.csv' THEN (
                    SELECT COUNT(*) FROM CALIBRATION_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'breakdowns.csv' THEN (
                    SELECT COUNT(*) FROM BREAKDOWNS_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'downtime.csv' THEN (
                    SELECT COUNT(*) FROM DOWNTIME_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
