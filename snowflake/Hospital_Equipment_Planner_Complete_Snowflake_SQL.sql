CREATE OR REPLACE PROCEDURE REGISTER_MANIFEST(P_RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN

    MERGE INTO INGESTION_RUN_CONTROL T
    USING (
        SELECT
            RAW_MANIFEST:run_id::VARCHAR AS RUN_ID,
            ARRAY_SIZE(OBJECT_KEYS(RAW_MANIFEST:files)) AS EXPECTED_FILES
        FROM MANIFEST_INGEST_STG
        WHERE RAW_MANIFEST:run_id::VARCHAR = :P_RUN_ID
        QUALIFY ROW_NUMBER() OVER (
            ORDER BY INGESTED_AT DESC
        ) = 1
    ) S
    ON T.RUN_ID = S.RUN_ID

    WHEN MATCHED THEN UPDATE SET
        T.EXPECTED_FILES = S.EXPECTED_FILES

    WHEN NOT MATCHED THEN INSERT (
        RUN_ID, EXPECTED_FILES, LOADED_FILES, RUN_STATUS
    )
    VALUES (
        S.RUN_ID, S.EXPECTED_FILES, 0, 'IN_PROGRESS'
    );

    MERGE INTO INGESTION_FILE_CONTROL T
    USING (
        SELECT
            M.RAW_MANIFEST:run_id::VARCHAR AS RUN_ID,
            F.KEY::VARCHAR AS FILE_NAME,
            F.VALUE:rows::NUMBER AS EXPECTED_ROWS
        FROM MANIFEST_INGEST_STG M,
             LATERAL FLATTEN(INPUT => M.RAW_MANIFEST:files) F
        WHERE M.RAW_MANIFEST:run_id::VARCHAR = :P_RUN_ID
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY F.KEY
            ORDER BY M.INGESTED_AT DESC
        ) = 1
    ) S
    ON T.RUN_ID = S.RUN_ID
       AND T.FILE_NAME = S.FILE_NAME

    WHEN MATCHED THEN UPDATE SET
        T.EXPECTED_ROWS = S.EXPECTED_ROWS

    WHEN NOT MATCHED THEN INSERT (
        RUN_ID, FILE_NAME, EXPECTED_ROWS, LOADED_ROWS, FILE_STATUS
    )
    VALUES (
        S.RUN_ID, S.FILE_NAME, S.EXPECTED_ROWS, 0, 'PENDING'
    );

    RETURN 'SUCCESS: Manifest registered for run ' || P_RUN_ID;

END;
$$;

CREATE OR REPLACE PROCEDURE PROMOTE_FULL_SNAPSHOT(P_RUN_ID VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
DECLARE
    V_STATUS VARCHAR;
    V_FILE_COUNT NUMBER;
    V_BAD_FILES NUMBER;
    V_EXPECTED_FILES NUMBER;
BEGIN

    SELECT RUN_STATUS, EXPECTED_FILES
    INTO :V_STATUS, :V_EXPECTED_FILES
    FROM INGESTION_RUN_CONTROL
    WHERE RUN_ID = :P_RUN_ID;

    IF (V_STATUS <> 'READY_FOR_PROMOTION') THEN
        RETURN 'ERROR: Run is not ready for promotion.';
    END IF;

    SELECT
        COUNT(*),
        COUNT_IF(
            FILE_STATUS <> 'LOADED'
            OR LOADED_ROWS <> EXPECTED_ROWS
        )
    INTO :V_FILE_COUNT, :V_BAD_FILES
    FROM INGESTION_FILE_CONTROL
    WHERE RUN_ID = :P_RUN_ID;

    IF (V_FILE_COUNT <> V_EXPECTED_FILES OR V_FILE_COUNT <> 10) THEN
        RETURN 'ERROR: Expected file count does not match.';
    END IF;

    IF (V_BAD_FILES > 0) THEN
        RETURN 'ERROR: One or more files failed row-count validation.';
    END IF;

    BEGIN TRANSACTION;

    DELETE FROM EQUIPMENT_LATEST;
    DELETE FROM USAGE_CLEAN_LATEST;
    DELETE FROM MAINTENANCE_LATEST;
    DELETE FROM CALIBRATION_LATEST;
    DELETE FROM BREAKDOWNS_LATEST;
    DELETE FROM DOWNTIME_LATEST;
    DELETE FROM DEPARTMENT_HISTORY_LATEST;
    DELETE FROM ASSET_DAY_UTILIZATION_LATEST;
    DELETE FROM DEPARTMENT_DAY_UTILIZATION_LATEST;
    DELETE FROM MAINTENANCE_COMPLIANCE_LATEST;

    INSERT INTO EQUIPMENT_LATEST
    SELECT
        ASSET_TAG, NAME, CATEGORY, DEPARTMENT, LIFECYCLE_STATUS,
        MANUFACTURER, MODEL, PURCHASE_DATE, PURCHASE_COST, WARRANTY_END,
        CONTRACT_TYPE, CONTRACT_END, LOCATION, MAINTENANCE_INTERVAL_DAYS,
        MAINTENANCE_THRESHOLD_HOURS, USAGE_HOURS_SINCE_MAINTENANCE,
        LAST_MAINTENANCE_AT, NEXT_MAINTENANCE_DUE, CALIBRATION_REQUIRED,
        LAST_CALIBRATION_AT, NEXT_CALIBRATION_DUE, CALIBRATION_FAILED,
        IN_SERVICE_FROM, RETIRED_AT
    FROM EQUIPMENT_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO USAGE_CLEAN_LATEST
    SELECT
        USAGE_ID, ASSET_TAG, DEPARTMENT, START_AT, END_AT,
        SOURCE, BATCH_ID, DURATION_H, USER_KEY
    FROM USAGE_CLEAN_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO MAINTENANCE_LATEST
    SELECT
        MAINTENANCE_ID, ASSET_TAG, KIND, PRIORITY, STATUS,
        SCHEDULED_START, SCHEDULED_END, ACTUAL_START, ACTUAL_END,
        NEXT_DUE_DATE, COMPLETED_ON_TIME, DURATION_H, ENGINEER_KEY
    FROM MAINTENANCE_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO CALIBRATION_LATEST
    SELECT
        CALIBRATION_ID, ASSET_TAG, STATUS, RESULT, SCHEDULED_FOR,
        PERFORMED_AT, NEXT_DUE_DATE, CERTIFICATE_NUMBER, ENGINEER_KEY
    FROM CALIBRATION_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO BREAKDOWNS_LATEST
    SELECT
        WORK_ORDER_ID, ASSET_TAG, PRIORITY, SEVERITY, UNSAFE,
        STATUS, REPORTED_AT, TRIAGED_AT, STARTED_AT, RESOLVED_AT,
        VERIFIED_AT, CLOSED_AT, DOWNTIME_HOURS, RESOLUTION_H,
        REPORTER_KEY, ENGINEER_KEY
    FROM BREAKDOWNS_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO DOWNTIME_LATEST
    SELECT
        DOWNTIME_ID, ASSET_TAG, START_AT, END_AT, REASON, DURATION_H
    FROM DOWNTIME_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO DEPARTMENT_HISTORY_LATEST
    SELECT
        ASSET_TAG, DEPARTMENT, EFFECTIVE_FROM, EFFECTIVE_TO
    FROM DEPARTMENT_HISTORY_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO ASSET_DAY_UTILIZATION_LATEST
    SELECT
        DAY, ASSET_TAG, DEPARTMENT, TOTAL_H, UNAVAILABLE_H,
        AVAILABLE_H, USED_H, IDLE_H, UTILIZATION, FLAG
    FROM ASSET_DAY_UTILIZATION_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO DEPARTMENT_DAY_UTILIZATION_LATEST
    SELECT
        DAY, DEPARTMENT, TOTAL_H, UNAVAILABLE_H, AVAILABLE_H,
        USED_H, IDLE_H, UTILIZATION, FLAG
    FROM DEPARTMENT_DAY_UTILIZATION_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    INSERT INTO MAINTENANCE_COMPLIANCE_LATEST
    SELECT
        METRIC, VALUE
    FROM MAINTENANCE_COMPLIANCE_INGEST_STG
    WHERE SOURCE_RUN_ID = :P_RUN_ID;

    UPDATE INGESTION_RUN_CONTROL
    SET
        RUN_STATUS = 'PROMOTED',
        PROMOTED_AT = CURRENT_TIMESTAMP()
    WHERE RUN_ID = :P_RUN_ID;

    COMMIT;

    RETURN 'SUCCESS: All 10 reporting tables promoted for run ' || P_RUN_ID;

EXCEPTION
    WHEN OTHER THEN
        ROLLBACK;
        RETURN 'ERROR: Promotion failed. ' || SQLERRM;
END;
$$;

