CREATE OR REPLACE VIEW VW_EQUIPMENT_OVERVIEW AS
SELECT
    ASSET_TAG,
    NAME AS EQUIPMENT_NAME,
    CATEGORY,
    DEPARTMENT,
    LIFECYCLE_STATUS,
    MANUFACTURER,
    MODEL,
    MAINTENANCE_INTERVAL_DAYS,
    NEXT_MAINTENANCE_DUE,
    CALIBRATION_REQUIRED
FROM EQUIPMENT_LATEST;

CREATE OR REPLACE VIEW VW_EQUIPMENT_UTILIZATION AS
SELECT
    E.ASSET_TAG,
    E.NAME AS EQUIPMENT_NAME,
    E.CATEGORY,
    E.DEPARTMENT,
    E.MANUFACTURER,
    E.MODEL,
    E.LIFECYCLE_STATUS,

    SUM(U.TOTAL_H) AS TOTAL_HOURS,
    SUM(U.AVAILABLE_H) AS AVAILABLE_HOURS,
    SUM(U.UNAVAILABLE_H) AS UNAVAILABLE_HOURS,
    SUM(U.USED_H) AS USED_HOURS,

    SUM(U.IDLE_H) AS IDLE_HOURS,

    CASE
        WHEN SUM(U.AVAILABLE_H) = 0 THEN NULL
        ELSE SUM(U.USED_H) / SUM(U.AVAILABLE_H) * 100
    END AS UTILIZATION_PERCENTAGE,

    MAX(U.FLAG) AS UTILIZATION_FLAG

FROM EQUIPMENT_LATEST E
LEFT JOIN ASSET_DAY_UTILIZATION_LATEST U
    ON E.ASSET_TAG = U.ASSET_TAG

GROUP BY
    E.ASSET_TAG,
    E.NAME,
    E.CATEGORY,
    E.DEPARTMENT,
    E.MANUFACTURER,
    E.MODEL,
    E.LIFECYCLE_STATUS;

CREATE OR REPLACE VIEW VW_DEPARTMENT_UTILIZATION AS
SELECT
    DEPARTMENT,
    SUM(TOTAL_H) AS TOTAL_HOURS,
    SUM(AVAILABLE_H) AS AVAILABLE_HOURS,
    SUM(UNAVAILABLE_H) AS UNAVAILABLE_HOURS,
    SUM(USED_H) AS USED_HOURS,
    SUM(IDLE_H) AS IDLE_HOURS,

    CASE
        WHEN SUM(AVAILABLE_H) = 0 THEN NULL
        ELSE SUM(USED_H) / SUM(AVAILABLE_H) * 100
    END AS UTILIZATION_PERCENTAGE

FROM DEPARTMENT_DAY_UTILIZATION_LATEST

GROUP BY DEPARTMENT;

CREATE OR REPLACE VIEW VW_DAILY_UTILIZATION_TREND AS
SELECT
    DAY,
    SUM(TOTAL_H) AS TOTAL_HOURS,
    SUM(AVAILABLE_H) AS AVAILABLE_HOURS,
    SUM(UNAVAILABLE_H) AS UNAVAILABLE_HOURS,
    SUM(USED_H) AS USED_HOURS,
    SUM(IDLE_H) AS IDLE_HOURS,

    CASE
        WHEN SUM(AVAILABLE_H) = 0 THEN NULL
        ELSE SUM(USED_H) / SUM(AVAILABLE_H) * 100
    END AS UTILIZATION_PERCENTAGE

FROM ASSET_DAY_UTILIZATION_LATEST
GROUP BY DAY;

CREATE OR REPLACE VIEW VW_MAINTENANCE_COMPLIANCE AS
SELECT
    SUM(CASE WHEN METRIC = 'completed'
        THEN VALUE ELSE 0 END) AS COMPLETED,

    SUM(CASE WHEN METRIC = 'completed_on_time'
        THEN VALUE ELSE 0 END) AS COMPLETED_ON_TIME,

    SUM(CASE WHEN METRIC = 'open_past_scheduled_end'
        THEN VALUE ELSE 0 END) AS OPEN_PAST_SCHEDULED_END,

    SUM(CASE WHEN METRIC = 'cancelled'
        THEN VALUE ELSE 0 END) AS CANCELLED,

    CASE
        WHEN SUM(CASE WHEN METRIC = 'completed'
            THEN VALUE ELSE 0 END) = 0 THEN NULL
        ELSE
            SUM(CASE WHEN METRIC = 'completed_on_time'
                THEN VALUE ELSE 0 END) * 100.0
            /
            SUM(CASE WHEN METRIC = 'completed'
                THEN VALUE ELSE 0 END)
    END AS ON_TIME_COMPLIANCE_PERCENTAGE

FROM MAINTENANCE_COMPLIANCE_LATEST;

CREATE OR REPLACE VIEW VW_DOWNTIME_ANALYSIS AS
SELECT
    D.DOWNTIME_ID,
    D.ASSET_TAG,
    E.NAME AS EQUIPMENT_NAME,
    E.CATEGORY,
    E.DEPARTMENT,
    E.MANUFACTURER,
    E.MODEL,
    D.START_AT,
    D.END_AT,
    D.REASON,
    D.DURATION_H,
    CASE
        WHEN D.END_AT IS NULL THEN 'ONGOING'
        ELSE 'CLOSED'
    END AS DOWNTIME_STATUS
FROM DOWNTIME_LATEST D
LEFT JOIN EQUIPMENT_LATEST E
    ON D.ASSET_TAG = E.ASSET_TAG;


