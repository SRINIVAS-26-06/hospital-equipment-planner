                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
            END > EXPECTED_ROWS THEN 'FAILED'

            ELSE 'PENDING'
        END,

        LOADED_AT = CASE
            WHEN FILE_STATUS = 'LOADED' THEN CURRENT_TIMESTAMP()
            ELSE NULL
        END

    WHERE RUN_ID = :P_RUN_ID;

    SELECT
        COUNT_IF(FILE_STATUS = 'LOADED'),
        COUNT(*),
        COUNT_IF(FILE_STATUS = 'FAILED'),
        COUNT_IF(FILE_STATUS = 'PENDING')
    INTO
        :V_LOADED_FILES,
        :V_TOTAL_FILES,
        :V_FAILED_FILES,
        :V_PENDING_FILES
    FROM INGESTION_FILE_CONTROL
    WHERE RUN_ID = :P_RUN_ID;

    UPDATE INGESTION_RUN_CONTROL
    SET
        LOADED_FILES = :V_LOADED_FILES,
        RUN_STATUS = CASE
            WHEN :V_TOTAL_FILES = EXPECTED_FILES
             AND :V_LOADED_FILES = EXPECTED_FILES
            THEN 'READY_FOR_PROMOTION'
            WHEN :V_FAILED_FILES > 0
            THEN 'VALIDATION_FAILED'
            ELSE 'IN_PROGRESS'
        END,
        ERROR_MESSAGE = CASE
            WHEN :V_FAILED_FILES > 0
            THEN 'One or more files contain more rows than expected.'
            ELSE NULL
        END
    WHERE RUN_ID = :P_RUN_ID;

    RETURN
        'Loaded: ' || V_LOADED_FILES ||
        '/' || V_TOTAL_FILES ||
        ', Pending: ' || V_PENDING_FILES ||
        ', Failed: ' || V_FAILED_FILES;

END;
$$;

CREATE OR REPLACE PROCEDURE PROCESS_PENDING_INGESTION_RUNS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_RUN_ID VARCHAR;
    V_STATUS VARCHAR;
    V_LATEST_PROMOTED_RUN VARCHAR;
    V_RESULT VARCHAR;

    V_REGISTERED NUMBER DEFAULT 0;
    V_VALIDATED NUMBER DEFAULT 0;
    V_PROMOTED NUMBER DEFAULT 0;

    RS_NEW RESULTSET;
    RS_RUNS RESULTSET;

BEGIN

    RS_NEW := (
        SELECT DISTINCT
            RAW_MANIFEST:run_id::VARCHAR AS RUN_ID
        FROM MANIFEST_INGEST_STG
        WHERE RAW_MANIFEST:run_id IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM INGESTION_RUN_CONTROL C
              WHERE C.RUN_ID = RAW_MANIFEST:run_id::VARCHAR
          )
    );

    FOR REC IN RS_NEW DO

        V_RUN_ID := REC.RUN_ID;

        CALL REGISTER_MANIFEST(:V_RUN_ID)
            INTO :V_RESULT;

        V_REGISTERED := V_REGISTERED + 1;

    END FOR;

    RS_RUNS := (
        SELECT RUN_ID, RUN_STATUS
        FROM INGESTION_RUN_CONTROL
        WHERE RUN_STATUS IN (
            'IN_PROGRESS',
            'READY_FOR_PROMOTION'
        )
        ORDER BY RUN_ID
    );

    FOR REC IN RS_RUNS DO

        V_RUN_ID := REC.RUN_ID;
        V_STATUS := REC.RUN_STATUS;

        IF (V_STATUS = 'IN_PROGRESS') THEN

            CALL VALIDATE_INGESTION_RUN(:V_RUN_ID)
                INTO :V_RESULT;

            V_VALIDATED := V_VALIDATED + 1;

        END IF;

        SELECT RUN_STATUS
        INTO :V_STATUS
        FROM INGESTION_RUN_CONTROL
        WHERE RUN_ID = :V_RUN_ID;

        IF (V_STATUS = 'READY_FOR_PROMOTION') THEN

            SELECT MAX(RUN_ID)
            INTO :V_LATEST_PROMOTED_RUN
            FROM INGESTION_RUN_CONTROL
            WHERE RUN_STATUS = 'PROMOTED';

            IF (
                V_LATEST_PROMOTED_RUN IS NULL
                OR V_RUN_ID > V_LATEST_PROMOTED_RUN
            ) THEN

                CALL PROMOTE_FULL_SNAPSHOT(:V_RUN_ID)
                    INTO :V_RESULT;

                IF (V_RESULT LIKE 'SUCCESS:%') THEN
                    V_PROMOTED := V_PROMOTED + 1;
                END IF;

            ELSE

                UPDATE INGESTION_RUN_CONTROL
                SET
                    RUN_STATUS = 'SUPERSEDED',
                    ERROR_MESSAGE =
                        'A newer snapshot has already been promoted.'
                WHERE RUN_ID = :V_RUN_ID;

            END IF;

        END IF;

    END FOR;

    RETURN
        'Orchestration completed. Registered: '
        || V_REGISTERED
        || ', Validated: '
        || V_VALIDATED
        || ', Promoted: '
        || V_PROMOTED;

END;
$$;

