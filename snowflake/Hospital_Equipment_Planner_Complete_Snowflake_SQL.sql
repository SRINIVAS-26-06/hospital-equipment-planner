                    WHERE SOURCE_RUN_ID = :P_RUN_ID
                )
                WHEN 'asset_day_utilization.csv' THEN (
                    SELECT COUNT(*) FROM ASSET_DAY_UTILIZATION_INGEST_STG
                    WHERE SOURCE_RUN_ID = :P_RUN_ID
