CREATE OR REPLACE PROCEDURE PROCESS_PENDING_INCREMENTAL_BATCHES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    v_candidate VARIANT;
    v_manifest VARIANT;
    v_batch_id VARCHAR(100);
    v_source_file VARCHAR(2000);
    v_pending_count NUMBER DEFAULT 0;

    v_dataset_count NUMBER DEFAULT 0;
    v_distinct_targets NUMBER DEFAULT 0;
    v_total_rows NUMBER DEFAULT 0;

    v_expected_equipment NUMBER DEFAULT -1;
    v_expected_usage NUMBER DEFAULT -1;
    v_expected_maintenance NUMBER DEFAULT -1;
    v_expected_calibration NUMBER DEFAULT -1;
    v_expected_breakdowns NUMBER DEFAULT -1;
    v_expected_downtime NUMBER DEFAULT -1;
    v_expected_history NUMBER DEFAULT -1;
    v_expected_asset_util NUMBER DEFAULT -1;
    v_expected_dept_util NUMBER DEFAULT -1;
    v_expected_compliance NUMBER DEFAULT -1;

    v_actual_equipment NUMBER DEFAULT 0;
    v_actual_usage NUMBER DEFAULT 0;
    v_actual_maintenance NUMBER DEFAULT 0;
    v_actual_calibration NUMBER DEFAULT 0;
    v_actual_breakdowns NUMBER DEFAULT 0;
    v_actual_downtime NUMBER DEFAULT 0;
    v_actual_history NUMBER DEFAULT 0;
    v_actual_asset_util NUMBER DEFAULT 0;
    v_actual_dept_util NUMBER DEFAULT 0;
    v_actual_compliance NUMBER DEFAULT 0;

    v_min_day DATE;
    v_max_day DATE;

    v_tx_started BOOLEAN DEFAULT FALSE;
    v_error VARCHAR(4000);

BEGIN

SELECT COUNT(*)
INTO :v_pending_count
FROM (
    SELECT
        RAW_MANIFEST:batch_id::STRING AS BATCH_ID
    FROM INCREMENTAL_BATCH_MANIFEST_STG M
    WHERE RAW_MANIFEST:status::STRING = 'COMPLETE'
      AND NOT EXISTS (
          SELECT 1
          FROM INCREMENTAL_BATCH_CONTROL C
          WHERE C.BATCH_ID = M.RAW_MANIFEST:batch_id::STRING
            AND C.STATUS = 'APPLIED'
      )
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY RAW_MANIFEST:batch_id::STRING
        ORDER BY LOADED_AT DESC
    ) = 1
);

IF (v_pending_count = 0) THEN
    RETURN 'No pending COMPLETE incremental batches.';
END IF;


SELECT
    RAW_MANIFEST,
    RAW_MANIFEST:batch_id::STRING,
    RAW_MANIFEST:source_file::STRING
INTO
    :v_manifest,
    :v_batch_id,
    :v_source_file
FROM INCREMENTAL_BATCH_MANIFEST_STG M
WHERE RAW_MANIFEST:status::STRING = 'COMPLETE'
  AND NOT EXISTS (
      SELECT 1
      FROM INCREMENTAL_BATCH_CONTROL C
      WHERE C.BATCH_ID = M.RAW_MANIFEST:batch_id::STRING
        AND C.STATUS = 'APPLIED'
  )
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY RAW_MANIFEST:batch_id::STRING
    ORDER BY LOADED_AT DESC
) = 1
ORDER BY LOADED_AT
LIMIT 1;


    IF (
        v_batch_id IS NULL OR
        v_source_file IS NULL OR
        v_manifest:status::STRING <> 'COMPLETE'
    ) THEN
        RETURN 'Invalid manifest: missing batch ID, source file, or COMPLETE status.';
    END IF;

    SELECT
        COUNT(*),
        COUNT(DISTINCT F.VALUE:target_table::STRING)
    INTO
        :v_dataset_count,
        :v_distinct_targets
    FROM TABLE(FLATTEN(INPUT => GET(:v_manifest, 'datasets'))) F;

    IF (
        v_dataset_count <> 10 OR
        v_distinct_targets <> 10
    ) THEN
        RETURN 'Manifest validation failed for batch '
               || v_batch_id
               || ': expected ten distinct datasets.';
    END IF;

    SELECT
        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'EQUIPMENT_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'USAGE_CLEAN_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'MAINTENANCE_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'CALIBRATION_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'BREAKDOWNS_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'DOWNTIME_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'DEPARTMENT_HISTORY_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'ASSET_DAY_UTILIZATION_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'DEPARTMENT_DAY_UTILIZATION_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(MAX(IFF(
            VALUE:target_table::STRING = 'MAINTENANCE_COMPLIANCE_LATEST',
            VALUE:row_count::NUMBER, NULL)), -1),

        COALESCE(SUM(VALUE:row_count::NUMBER), 0)

    INTO
        :v_expected_equipment,
        :v_expected_usage,
        :v_expected_maintenance,
        :v_expected_calibration,
        :v_expected_breakdowns,
        :v_expected_downtime,
        :v_expected_history,
        :v_expected_asset_util,
        :v_expected_dept_util,
        :v_expected_compliance,
        :v_total_rows

    FROM TABLE(FLATTEN(INPUT => GET(:v_manifest, 'datasets')));


    IF (
        v_expected_equipment < 0 OR
        v_expected_usage < 0 OR
        v_expected_maintenance < 0 OR
        v_expected_calibration < 0 OR
        v_expected_breakdowns < 0 OR
        v_expected_downtime < 0 OR
        v_expected_history < 0 OR
        v_expected_asset_util < 0 OR
        v_expected_dept_util < 0 OR
        v_expected_compliance < 0
    ) THEN
        RETURN 'Manifest is missing one or more expected datasets for batch '
               || v_batch_id;
    END IF;

    SELECT COUNT(*) INTO :v_actual_equipment
    FROM EQUIPMENT_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_usage
    FROM USAGE_CLEAN_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_maintenance
    FROM MAINTENANCE_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_calibration
    FROM CALIBRATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_breakdowns
    FROM BREAKDOWNS_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_downtime
    FROM DOWNTIME_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_history
    FROM DEPARTMENT_HISTORY_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_asset_util
    FROM ASSET_DAY_UTILIZATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_dept_util
    FROM DEPARTMENT_DAY_UTILIZATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    SELECT COUNT(*) INTO :v_actual_compliance
    FROM MAINTENANCE_COMPLIANCE_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

  IF (
        v_actual_equipment <> v_expected_equipment OR
        v_actual_usage <> v_expected_usage OR
        v_actual_maintenance <> v_expected_maintenance OR
        v_actual_calibration <> v_expected_calibration OR
        v_actual_breakdowns <> v_expected_breakdowns OR
        v_actual_downtime <> v_expected_downtime OR
        v_actual_history <> v_expected_history OR
        v_actual_asset_util <> v_expected_asset_util OR
        v_actual_dept_util <> v_expected_dept_util OR
        v_actual_compliance <> v_expected_compliance
    ) THEN
        RETURN 'WAIT: Batch ' || v_batch_id
               || ' is not fully loaded. Expected and actual row counts differ.';
    END IF;

    SELECT
        MIN(DAY),
        MAX(DAY)
    INTO
        :v_min_day,
        :v_max_day
    FROM ASSET_DAY_UTILIZATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    IF (v_min_day IS NULL OR v_max_day IS NULL) THEN
        RETURN 'WAIT: No asset-day utilization rows found for batch '
               || v_batch_id;
    END IF;

  BEGIN TRANSACTION;
    v_tx_started := TRUE;

    MERGE INTO INCREMENTAL_BATCH_CONTROL T
    USING (
        SELECT
            :v_batch_id AS BATCH_ID,
            :v_source_file AS SOURCE_FILE_NAME
    ) S
    ON T.BATCH_ID = S.BATCH_ID

    WHEN MATCHED THEN UPDATE SET
        T.SOURCE_FILE_NAME = S.SOURCE_FILE_NAME,
        T.STATUS = 'PROCESSING',
        T.EXPECTED_DATASET_COUNT = 10,
        T.TOTAL_ROWS = :v_total_rows,
        T.STARTED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
        T.APPLIED_AT = NULL,
        T.ERROR_MESSAGE = NULL

    WHEN NOT MATCHED THEN INSERT (
        BATCH_ID,
        SOURCE_FILE_NAME,
        STATUS,
        EXPECTED_DATASET_COUNT,
        TOTAL_ROWS,
        STARTED_AT
    )
    VALUES (
        S.BATCH_ID,
        S.SOURCE_FILE_NAME,
        'PROCESSING',
        10,
        :v_total_rows,
        CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
    );



    DELETE FROM EQUIPMENT_LATEST;

    INSERT INTO EQUIPMENT_LATEST
    SELECT
        ASSET_TAG, NAME, CATEGORY, DEPARTMENT, LIFECYCLE_STATUS,
        MANUFACTURER, MODEL, PURCHASE_DATE, PURCHASE_COST, WARRANTY_END,
        CONTRACT_TYPE, CONTRACT_END, LOCATION, MAINTENANCE_INTERVAL_DAYS,
        LAST_MAINTENANCE_AT, NEXT_MAINTENANCE_DUE, CALIBRATION_REQUIRED,
        LAST_CALIBRATION_AT, NEXT_CALIBRATION_DUE, CALIBRATION_FAILED,
        IN_SERVICE_FROM, RETIRED_AT, MAINTENANCE_THRESHOLD_HOURS,
        USAGE_HOURS_SINCE_MAINTENANCE
    FROM EQUIPMENT_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM USAGE_CLEAN_LATEST;

    INSERT INTO USAGE_CLEAN_LATEST
    SELECT
        USAGE_ID, ASSET_TAG, DEPARTMENT, START_AT, END_AT,
        SOURCE, BATCH_ID, USER_KEY, DURATION_H
    FROM USAGE_CLEAN_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM MAINTENANCE_LATEST;

    INSERT INTO MAINTENANCE_LATEST
    SELECT
        MAINTENANCE_ID, ASSET_TAG, KIND, PRIORITY, STATUS,
        SCHEDULED_START, SCHEDULED_END, ACTUAL_START, ACTUAL_END,
        NEXT_DUE_DATE, COMPLETED_ON_TIME, DURATION_H, ENGINEER_KEY
    FROM MAINTENANCE_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM CALIBRATION_LATEST;

    INSERT INTO CALIBRATION_LATEST
    SELECT
        CALIBRATION_ID, ASSET_TAG, STATUS, RESULT, SCHEDULED_FOR,
        PERFORMED_AT, NEXT_DUE_DATE, CERTIFICATE_NUMBER, ENGINEER_KEY
    FROM CALIBRATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM BREAKDOWNS_LATEST;

    INSERT INTO BREAKDOWNS_LATEST
    SELECT
        WORK_ORDER_ID, ASSET_TAG, PRIORITY, SEVERITY, UNSAFE, STATUS,
        REPORTED_AT, TRIAGED_AT, STARTED_AT, RESOLVED_AT, VERIFIED_AT,
        CLOSED_AT, DOWNTIME_HOURS, RESOLUTION_H, REPORTER_KEY, ENGINEER_KEY
    FROM BREAKDOWNS_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM DOWNTIME_LATEST;

    INSERT INTO DOWNTIME_LATEST
    SELECT
        DOWNTIME_ID, ASSET_TAG, START_AT, END_AT, REASON, DURATION_H
    FROM DOWNTIME_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM DEPARTMENT_HISTORY_LATEST;

    INSERT INTO DEPARTMENT_HISTORY_LATEST
    SELECT
        ASSET_TAG, DEPARTMENT, EFFECTIVE_FROM, EFFECTIVE_TO
    FROM DEPARTMENT_HISTORY_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM ASSET_DAY_UTILIZATION_LATEST
    WHERE DAY BETWEEN :v_min_day AND :v_max_day;

    INSERT INTO ASSET_DAY_UTILIZATION_LATEST
    SELECT
        DAY, ASSET_TAG, DEPARTMENT, TOTAL_H, UNAVAILABLE_H,
        AVAILABLE_H, USED_H, IDLE_H, UTILIZATION, FLAG
    FROM ASSET_DAY_UTILIZATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM DEPARTMENT_DAY_UTILIZATION_LATEST
    WHERE DAY BETWEEN :v_min_day AND :v_max_day;

    INSERT INTO DEPARTMENT_DAY_UTILIZATION_LATEST
    SELECT
        DAY, DEPARTMENT, TOTAL_H, UNAVAILABLE_H, AVAILABLE_H,
        USED_H, IDLE_H, UTILIZATION, FLAG
    FROM DEPARTMENT_DAY_UTILIZATION_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';


    DELETE FROM MAINTENANCE_COMPLIANCE_LATEST;

    INSERT INTO MAINTENANCE_COMPLIANCE_LATEST
    SELECT
        METRIC,
        VALUE
    FROM MAINTENANCE_COMPLIANCE_INCREMENTAL_STG
    WHERE SOURCE_FILE_NAME = :v_source_file
      AND OPERATION = 'UPSERT';

    UPDATE INCREMENTAL_BATCH_CONTROL
    SET
        STATUS = 'APPLIED',
        APPLIED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
        ERROR_MESSAGE = NULL
    WHERE BATCH_ID = :v_batch_id;

    COMMIT;

    v_tx_started := FALSE;

    RETURN 'SUCCESS: Batch ' || v_batch_id
           || ' promoted. Total rows: ' || v_total_rows;


EXCEPTION
    WHEN OTHER THEN

        v_error := SQLERRM;

        IF (v_tx_started) THEN
            ROLLBACK;
        END IF;

        IF (v_batch_id IS NOT NULL) THEN

            MERGE INTO INCREMENTAL_BATCH_CONTROL T
            USING (
                SELECT
                    :v_batch_id AS BATCH_ID,
                    :v_source_file AS SOURCE_FILE_NAME
            ) S
            ON T.BATCH_ID = S.BATCH_ID

            WHEN MATCHED THEN UPDATE SET
                T.STATUS = 'FAILED',
                T.ERROR_MESSAGE = LEFT(:v_error, 4000)

            WHEN NOT MATCHED THEN INSERT (
                BATCH_ID,
                SOURCE_FILE_NAME,
                STATUS,
                EXPECTED_DATASET_COUNT,
                TOTAL_ROWS,
                STARTED_AT,
                ERROR_MESSAGE
            )
            VALUES (
                S.BATCH_ID,
                S.SOURCE_FILE_NAME,
                'FAILED',
                10,
                0,
                CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
                LEFT(:v_error, 4000)
            );

        END IF;

        RETURN 'FAILED: Batch '
               || COALESCE(v_batch_id, 'UNKNOWN')
               || '. Error: ' || v_error;

END;
$$;

CREATE OR REPLACE TASK INCREMENTAL_BATCH_PROMOTION_TASK
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '1 MINUTE'
    ALLOW_OVERLAPPING_EXECUTION = FALSE
AS
    CALL PROCESS_PENDING_INCREMENTAL_BATCHES();

ALTER TASK INCREMENTAL_BATCH_PROMOTION_TASK RESUME;


SHOW PIPES IN SCHEMA HOSPITAL_EQUIPMENT_DB.ANALYTICS;
SHOW TASKS IN SCHEMA HOSPITAL_EQUIPMENT_DB.ANALYTICS;

SELECT TABLE_NAME, ROW_COUNT
FROM HOSPITAL_EQUIPMENT_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'ANALYTICS'
